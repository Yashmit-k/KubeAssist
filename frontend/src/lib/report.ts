/**
 * Incident reports as Markdown, for pasting into an incident doc,
 * ticket or chat. Built only from what KubeAssist already showed the
 * user; commands are listed as suggestions, never as things that ran.
 */
import { failureLabel, modeLabel } from "./format";
import type { Diagnosis, FixStep, ScanResult, VerifyResult } from "./types";

const FOOTER = "_Generated by KubeAssist (read-only). Commands are suggestions for a human to review and run; KubeAssist executed nothing._";

const VERDICT_TEXT: Record<VerifyResult["verdict"], string> = {
  fixed: "✅ Fixed",
  starting: "⏳ Starting",
  still_failing: "❌ Still failing",
  new_problem: "⚠️ New problem",
  not_found: "Pod gone",
};

function steps(list: Pick<FixStep, "description" | "command" | "isWriteAction">[]): string[] {
  const out: string[] = [];
  list.forEach((s, i) => {
    out.push(`${i + 1}. ${s.description}${s.isWriteAction ? " _(changes the cluster)_" : ""}`);
    if (s.command) out.push("", "   ```bash", `   ${s.command}`, "   ```");
  });
  return out;
}

function stamp(d: Date): string {
  return d.toISOString().replace("T", " ").replace(/\.\d+Z$/, " UTC");
}

export type DiagnosisReportInput = {
  cluster: string;
  namespace: string;
  pod: string;
  diagnosis: Diagnosis;
  question?: string;
  verify?: VerifyResult | null;
  generatedAt?: Date;
};

export function diagnosisReport(o: DiagnosisReportInput): string {
  const d = o.diagnosis;
  const lines = [
    `# ${failureLabel(d.failureType)}: ${o.namespace}/${o.pod}`,
    "",
    `- **Cluster:** ${o.cluster}`,
    `- **Pod:** \`${o.namespace}/${o.pod}\``,
    `- **Failure type:** \`${d.failureType}\` (confidence ${Math.round(d.confidenceScore * 100)}%)`,
    `- **Diagnosis:** ${modeLabel(d.mode).label}`,
    `- **Report generated:** ${stamp(o.generatedAt ?? new Date())}`,
  ];
  if (o.question) lines.push(`- **Question asked:** ${o.question}`);
  lines.push("", "## Summary", "", d.issueSummary);
  if (d.observedEvidence.length) lines.push("", "## Evidence", "", ...d.observedEvidence.map((e) => `- ${e}`));
  lines.push("", "## Root cause", "", d.probableRootCause);
  if (d.reasoning) lines.push("", d.reasoning);
  const fix = [...(d.resolutionSteps ?? [])].sort((a, b) => a.order - b.order);
  if (fix.length) lines.push("", "## Fix", "", ...steps(fix.map((s) => ({ ...s, isWriteAction: !!s.isWriteAction }))));
  if (d.verificationCommands.length) lines.push("", "## How to verify", "", ...d.verificationCommands.map((c) => `- \`${c}\``));
  if (o.verify) {
    const v = o.verify;
    lines.push("", "## Verification result", "", `**${VERDICT_TEXT[v.verdict]}** — checked ${stamp(new Date(v.checkedAt))}`, "", v.message);
    if (v.pod) lines.push("", `Pod \`${v.pod.name}\`: ${v.pod.status}, ready ${v.pod.ready}, restarts ${v.pod.restartCount}`);
  }
  if (d.rollbackGuidance) lines.push("", "## Rollback", "", d.rollbackGuidance);
  if (d.documentationReferences.length) lines.push("", "## References", "", ...d.documentationReferences.map((r) => `- [${r.title}](${r.url})`));
  if (d.uncertaintyNotes.length) lines.push("", "## Caveats", "", ...d.uncertaintyNotes.map((n) => `- ${n}`));
  lines.push("", "---", FOOTER, "");
  return lines.join("\n");
}

export function scanReport(o: { cluster: string; scan: ScanResult; generatedAt?: Date }): string {
  const s = o.scan;
  const broken = s.groups.reduce((n, g) => n + g.pods.length, 0);
  const lines = [
    `# Cluster health scan: ${o.cluster}`,
    "",
    `- **Scope:** ${s.namespace ? `namespace \`${s.namespace}\`` : "all namespaces"}`,
    `- **Scanned:** ${stamp(new Date(s.scannedAt))}`,
    `- **Pods in scope:** ${s.totalPods} · **unhealthy:** ${broken} · **root causes:** ${s.groups.length}`,
  ];
  if (s.truncated) lines.push("- Only the first 40 unhealthy pods were checked.");
  if (!s.groups.length) lines.push("", "No problems found: every pod is running and ready.");
  s.groups.forEach((g, i) => {
    lines.push("", `## ${i + 1}. ${g.title}`, "", `**${failureLabel(g.failureType)}** (\`${g.failureType}\`) — ${g.pods.length} pod${g.pods.length === 1 ? "" : "s"}:`, "");
    lines.push(...g.pods.map((p) => `- \`${p.namespace}/${p.name}\` — ${p.status}, ready ${p.ready}, restarts ${p.restartCount}`));
    if (g.evidence.length) lines.push("", "Evidence:", "", ...g.evidence.map((e) => `- ${e}`));
    if (g.fix?.steps?.length) lines.push("", "Fix:", "", ...steps(g.fix.steps));
  });
  if (s.errors.length) lines.push("", "## Pods that couldn't be checked", "", ...s.errors.map((e) => `- \`${e.namespace}/${e.name}\` — ${e.error}`));
  lines.push("", "---", FOOTER, "");
  return lines.join("\n");
}

/** A safe file name for a report. */
export function reportFileName(...parts: string[]): string {
  const slug = parts.join("-").toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/-+/g, "-").replace(/^-|-$/g, "");
  return `kubeassist-${slug || "report"}.md`;
}
